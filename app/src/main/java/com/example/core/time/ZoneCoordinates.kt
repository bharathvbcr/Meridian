    /**
     * Best-known coordinate for [zoneId] at [instant] (instant only affects the offset fallback,
     * so DST is respected). Always returns a usable point — never null.
     */
    fun coordinateFor(zoneId: String, instant: Instant): GeoPoint =
        KNOWN[zoneId] ?: offsetFallback(zoneId, instant)

    /**
     * The known IANA zone whose representative city is geographically closest to ([lat], [lng]).
     * Used to resolve a home zone from a device location offline (§5.1). Uses an equirectangular
     * approximation of distance, which is accurate enough for nearest-city selection.
     */
    fun nearestKnownZone(lat: Double, lng: Double): String =
        KNOWN.minByOrNull { (_, point) -> squaredDistance(lat, lng, point) }?.key
            ?: ZoneId.systemDefault().id

    private fun squaredDistance(lat: Double, lng: Double, point: GeoPoint): Double {
        val meanLatRad = (lat + point.latitude) / 2.0 * (Math.PI / 180.0)
        val dx = (lng - point.longitude) * cos(meanLatRad)
        val dy = lat - point.latitude
        return dx * dx + dy * dy
    }

    /** Exposed for callers that need the great-circle-ish distance directly. */
    fun distanceDegrees(lat: Double, lng: Double, point: GeoPoint): Double =
        sqrt(squaredDistance(lat, lng, point))

    private fun offsetFallback(zoneId: String, instant: Instant): GeoPoint {
        val zone = runCatching { ZoneId.of(zoneId) }.getOrDefault(ZoneId.of("UTC"))
        val offsetSeconds = zone.rules.getOffset(instant).totalSeconds
        val longitude = (offsetSeconds / 3600.0) * 15.0
        return GeoPoint(latitude = 0.0, longitude = longitude.coerceIn(-180.0, 180.0))
    }
