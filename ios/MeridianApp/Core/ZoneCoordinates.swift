// NOTE ON NAMING: SolarMath.swift already declares a `public struct ZoneCoordinates` with a small
// 25+ city table exposing `coordinates(for:) -> (lat:lon:)?` (consumed by GlobeView). To avoid a
// redeclaration collision while still delivering the FULL Android table + nearestKnownZone + offset
// fallback required by the zone-resolution stack, this comprehensive primitive is named `ZoneGeo`.
// It is the offline IANA-zone → coordinate authority for home-zone resolution and the day/night map.
// `GeoPoint` defined here is the shared coordinate value type used across the zone stack.

import Foundation

// NOTE: `GeoPoint` is declared canonically in SolarMath.swift (`public struct GeoPoint: Sendable,
// Equatable` with `init(latitude:longitude:)`). It was previously redeclared here, which is an
// invalid redeclaration since both files compile into the same module. The duplicate declaration
// has been removed; the additions the zone stack needs — the unlabeled `init(_:_:)` used ~400 times
// by the `known` table, and `Hashable` conformance — are layered on via the extension below so the
// single canonical type satisfies every caller in both files.

/// Decimal-degree coordinate conveniences for the zone stack (positive lat = North, positive lng = East).
// `Hashable` is added here (not `@retroactive`: `GeoPoint` is declared in this same module, in SolarMath.swift).
extension GeoPoint: Hashable {
    /// Unlabeled initializer used throughout the `known` table, e.g. `GeoPoint(5.3167, -4.0333)`.
    public init(_ latitude: Double, _ longitude: Double) {
        self.init(latitude: latitude, longitude: longitude)
    }

    // `Hashable` synthesis is unavailable for a conformance added in a different file from the type's
    // declaration, so `hash(into:)` is provided explicitly. `==` is already synthesized via the
    // `Equatable` conformance declared alongside the type in SolarMath.swift.
    public func hash(into hasher: inout Hasher) {
        hasher.combine(latitude)
        hasher.combine(longitude)
    }
}

/// Offline IANA-zone → representative coordinate lookup for the day/night map and offline home-zone
/// resolution. Privacy-friendly: no network. Unknown zones fall back to their standard meridian
/// (UTC offset × 15°) at the equator, a reasonable approximation for the terminator.
public enum ZoneGeo {

    /// Best-known coordinate for `zoneId` at `instant` (instant only affects the offset fallback, so
    /// DST is respected). Always returns a usable point — never nil.
    public static func coordinate(for zoneId: String, at instant: Date = .now) -> GeoPoint {
        known[zoneId] ?? offsetFallback(zoneId: zoneId, instant: instant)
    }

    /// Compatibility accessor mirroring the small `ZoneCoordinates.coordinates(for:)` shape, but
    /// backed by the full table. Returns nil for zones not explicitly known (no offset fallback).
    public static func coordinates(for zoneId: String) -> (lat: Double, lon: Double)? {
        known[zoneId].map { ($0.latitude, $0.longitude) }
    }

    /// The known IANA zone whose representative city is geographically closest to (`lat`, `lng`).
    /// Used to resolve a home zone from a device location offline. Equirectangular approximation,
    /// accurate enough for nearest-city selection.
    public static func nearestKnownZone(lat: Double, lng: Double) -> String {
        var bestKey = TimeZone.current.identifier
        var bestDist = Double.greatestFiniteMagnitude
        for (key, point) in known {
            let d = squaredDistance(lat: lat, lng: lng, point: point)
            if d < bestDist {
                bestDist = d
                bestKey = key
            }
        }
        return bestKey
    }

    /// Great-circle-ish distance in degrees for callers that need it directly.
    public static func distanceDegrees(lat: Double, lng: Double, point: GeoPoint) -> Double {
        squaredDistance(lat: lat, lng: lng, point: point).squareRoot()
    }

    // MARK: - Private

    private static func squaredDistance(lat: Double, lng: Double, point: GeoPoint) -> Double {
        let meanLatRad = (lat + point.latitude) / 2.0 * (Double.pi / 180.0)
        let dx = (lng - point.longitude) * cos(meanLatRad)
        let dy = lat - point.latitude
        return dx * dx + dy * dy
    }

    private static func offsetFallback(zoneId: String, instant: Date) -> GeoPoint {
        let zone = TimeZone(identifier: zoneId) ?? TimeZone(identifier: "UTC")!
        let offsetSeconds = zone.secondsFromGMT(for: instant)
        let longitude = (Double(offsetSeconds) / 3600.0) * 15.0
        return GeoPoint(latitude: 0.0, longitude: min(max(longitude, -180.0), 180.0))
    }

